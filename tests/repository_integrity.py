"""Current research scope of legacy whole-workspace receipts; never edit the receipts."""
from pathlib import Path, PureWindowsPath
from hashlib import sha256

HISTORICAL_ROOT = PureWindowsPath('D:/Project/wo-retrieval-benchmark')
EXTERNAL_CACHE = PureWindowsPath('D:/ModelCache/wo-retrieval-benchmark')


def research_baseline(root, historical):
    root = Path(root).resolve()
    hashes, excluded = {}, {}
    for original, expected in historical.items():
        path = PureWindowsPath(original)
        if path.is_relative_to(EXTERNAL_CACHE):
            excluded[original] = 'external encoding cache/runtime; environment-specific'
            continue
        relative = path.relative_to(HISTORICAL_ROOT)
        if not relative.parts or '..' in relative.parts:
            raise ValueError('Historical path traversal')
        if relative.as_posix() in ('README.md', '.gitignore'):
            excluded[original] = 'maintained documentation/publication rules'
        elif relative.parts[0] == 'tests':
            excluded[original] = 'maintained test implementation; executed separately'
        elif any(p == '__pycache__' or p.endswith('.egg-info') for p in relative.parts):
            excluded[original] = 'generated bytecode/installation metadata'
        else:
            current = root.joinpath(*relative.parts)
            if not current.resolve().is_relative_to(root) or not current.is_file() or sha256(current.read_bytes()).hexdigest() != expected:
                raise ValueError('Protected repository artifact changed: ' + relative.as_posix())
            hashes[str(current)] = expected
    if not hashes or len(hashes) + len(excluded) != len(historical):
        raise ValueError('Incomplete historical classification')
    return dict(hashes=hashes, excluded=excluded, historical_count=len(historical))
